/** Upstream has no CLI creation source; the CLI is a user-facing client like the web app. */
const ORIGIN = { createdBy: "user", creationSource: "web" } as const;

const TURN_FLAGS = {
  "prompt-file": { type: "string", value: "path", help: "read the prompt from a file instead of stdin" },
  attach: { type: "string", value: "path", multiple: true, help: "attach a file (png/jpg/gif/webp as images; others as files), repeatable" },
  "runtime-mode": { type: "string", value: "mode", help: `one of ${RUNTIME_MODES.join(", ")}` },
  "interaction-mode": { type: "string", value: "mode", help: `one of ${INTERACTION_MODES.join(", ")}` },
  wait: { type: "boolean", help: "block until the turn settles and print the assistant's reply" },
  timeout: { type: "string", value: "duration", help: "with --wait: give up after e.g. 30m, 2h (the turn keeps running)" },
} as const;

export const newThread: Command = {
  name: "new",
  summary: "Create a thread and start its first turn from the prompt on stdin. One launch creates the thread, the optional worktree, and the turn.",
  usage: "new --project <project> [model flags] [--title <text>] [--prepare-worktree ...] [turn flags] [--no-prompt] < prompt.md",
  flags: {
    project: { type: "string", value: "project", help: "project id, title, or workspace path" },
    title: { type: "string", value: "text", help: "thread title (default: first line of the prompt, then regenerated by the server)" },
    "prepare-worktree": { type: "boolean", help: "create a git worktree for this thread; runs the project's worktree setup script" },
    "base-branch": { type: "string", value: "ref", help: "with --prepare-worktree: ref to start from (default: main)" },
    branch: { type: "string", value: "name", help: "with --prepare-worktree: new branch name (default: server-generated)" },
    "start-from-origin": { type: "boolean", help: "with --prepare-worktree: fetch and start from origin/<base-branch>" },
    "no-prompt": { type: "boolean", help: "create an empty thread only (thread.create), no turn" },
    ...MODEL_FLAGS,
    ...TURN_FLAGS,
  },
  examples: [
    "t3c new --project t3code --instance-id codex --model gpt-6-astra --option reasoningEffort=high < brief.md",
    "t3c new --project . --instance-id claudeAgent --model claude-fable-5-1 --option effort=max --prepare-worktree --branch nei/fix --wait < brief.md",
    "echo 'Summarize README.md' | t3c new --project scratch --json",
  ],
  async run(context) {
    const { args, print } = context;
    const client = await context.client();
    const project = resolveProject(await client.shell(), requireFlag(args, "project"));
    const inherited = project.defaultModelSelection ?? (await client.call("server.getConfig", {})).settings.defaultModelSelection;
    const modelSelection = modelFromFlags(args, inherited) ?? (inherited as ModelSelection | null | undefined);
    if (!modelSelection) throw new UsageError("no model selected and the project has no default; pass --instance-id and --model (see: t3c models)");
    if (!boolFlag(args, "no-validate")) await checkModel(client, modelSelection);
    const noPrompt = boolFlag(args, "no-prompt");
    const text = noPrompt ? "" : await readPrompt(stringFlag(args, "prompt-file"));
    const explicitTitle = stringFlag(args, "title");
    const threadId = randomUUID();
    const thread = {
      threadId,
      projectId: project.id,
      title: explicitTitle ?? titleFromPrompt(text),
      modelSelection,
      runtimeMode: enumFlag(args, "runtime-mode", RUNTIME_MODES, "full-access"),
      interactionMode: enumFlag(args, "interaction-mode", INTERACTION_MODES, "default"),
    };
    if (noPrompt) {
      const result = await client.dispatch({ type: "thread.create", ...ORIGIN, ...thread, branch: null, worktreePath: null });
      print({ threadId, ...result }, () => threadId);
      return;
    }
    const messageId = randomUUID();
    await client.call("orchestration.launchThread", {
      commandId: randomUUID(),
      creationSource: ORIGIN.creationSource,
      ...thread,
      generateTitle: explicitTitle ? undefined : true,
      workspaceStrategy: boolFlag(args, "prepare-worktree")
        ? { type: "worktree", baseRef: stringFlag(args, "base-branch") ?? "main", branch: stringFlag(args, "branch"), startFromOrigin: boolFlag(args, "start-from-origin") || undefined }
        : { type: "root" },
      initialMessage: { messageId, text, attachments: await attachmentsFromPaths(client, listFlag(args, "attach")) },
    });
    return afterTurnStart(context, client, threadId, messageId);
  },
};

export const send: Command = {
  name: "send",
  summary: "Send a follow-up message to a thread with the prompt on stdin; it queues behind a running turn. Model and mode flags override the thread's settings.",
  usage: "send <thread> [model flags] [turn flags] [--from-plan <planId>] < prompt.md",
  flags: {
    "from-plan": { type: "string", value: "planId", help: "implement a plan this thread proposed (sets sourcePlanRef)" },
    ...MODEL_FLAGS,
    ...TURN_FLAGS,
  },
  examples: ["echo 'Also cover the reconnect path' | t3c send 8f0a --wait", "t3c send 8f0a --from-plan plan_123 --interaction-mode default --wait < /dev/null"],
  async run(context) {
    const { args } = context;
    const client = await context.client();
    const thread = await lookupThread(client, positional(args, 0, "thread"));
    const modelSelection = modelFromFlags(args, thread.modelSelection);
    if (modelSelection && !boolFlag(args, "no-validate")) await checkModel(client, modelSelection);
    const planId = stringFlag(args, "from-plan");
    const promptFile = stringFlag(args, "prompt-file");
    const text = planId && process.stdin.isTTY && !promptFile ? "" : await readPrompt(promptFile);
    const attachments = await attachmentsFromPaths(client, listFlag(args, "attach"));
    // Modes are thread settings now, not part of the message.
    const runtimeMode = enumFlag(args, "runtime-mode", RUNTIME_MODES);
    const interactionMode = enumFlag(args, "interaction-mode", INTERACTION_MODES);
    if (runtimeMode && runtimeMode !== thread.runtimeMode) await client.dispatch({ type: "thread.runtime-mode.set", threadId: thread.id, runtimeMode });
    if (interactionMode && interactionMode !== thread.interactionMode) await client.dispatch({ type: "thread.interaction-mode.set", threadId: thread.id, interactionMode });
    const messageId = randomUUID();
    const result = await client.dispatch({
      type: "message.dispatch",
      ...ORIGIN,
      threadId: thread.id,
      messageId,
      text,
      attachments,
      modelSelection,
      sourcePlanRef: planId ? { threadId: thread.id, planId } : undefined,
      // Without a deliveryIntent the server queues behind an active run instead of steering into it, so the message always gets its own run.
      dispatchMode: { type: "start_immediately" },
    });
    return afterTurnStart(context, client, thread.id, messageId, result.sequence);
  },
};

async function afterTurnStart(context: Context, client: T3Client, threadId: string, messageId: string, sequence?: number): Promise<number | void> {
  if (!boolFlag(context.args, "wait")) {
    context.print({ threadId, messageId, sequence }, () => threadId);
    return;
  }
  return reportOutcome(context, client, threadId, await waitOn(client, threadId, { messageId }, timeoutSignal(context.args)), sequence);
}

/** The stream opens with a snapshot taken after the subscription starts, so it already reflects anything dispatched before it. */
function waitOn(client: T3Client, threadId: string, target: Target, signal: AbortSignal | undefined): Promise<TurnOutcome | null> {
  return waitForTurn(client.stream("orchestration.subscribeThread", { threadId }, signal), target);
}

async function reportOutcome({ print }: Context, client: T3Client, threadId: string, outcome: TurnOutcome | null, sequence?: number): Promise<number> {
  if (!outcome) {
    print({ threadId, state: "timeout" }, () => `timed out waiting on ${threadId}; the turn is still running`);
    return EXIT.timeout;
  }
  const projection = await client.thread(threadId);
  const text = finalAssistantText(projection, outcome.runId);
  const files = projection.checkpoints.find((checkpoint) => checkpoint.runId === outcome.runId)?.files.length ?? 0;
  print({ threadId, ...outcome, sequence, text, files, title: projection.thread.title }, () => {
    if (outcome.state === "needs-input") {
      const lines = pendingRequests(projection).map(({ request }) => `  ${request.kind} ${request.id}`);
      return `${threadId} is waiting on:\n${lines.join("\n")}\n(use t3c pending, then t3c approve or t3c answer)`;
    }
    if (outcome.state === "failed") return `${threadId} failed: ${outcome.lastError ?? "unknown error"}\n\n${text}`;
    return text || `${threadId} ${outcome.state}`;
  });
  return EXIT_CODE_BY_OUTCOME[outcome.state];
}

export function titleFromPrompt(text: string, max = 80): string {
  const firstLine = text.split("\n").map((line) => line.replace(/^#+\s*/, "").trim()).find((line) => line.length > 0) ?? "Untitled thread";
  return firstLine.length > max ? `${firstLine.slice(0, max - 1)}…` : firstLine;
}

export const wait: Command = {
  name: "wait",
  summary: "Block until the thread's current turn settles. Exit 0 completed, 2 failed, 3 interrupted/cancelled/rolled back, 4 waiting on approval/input, 124 timeout.",
  usage: "wait <thread> [--timeout <duration>]",
  flags: { timeout: { type: "string", value: "duration", help: "give up after e.g. 30m (the turn keeps running)" } },
  async run(context) {
    const client = await context.client();
    const thread = await lookupThread(client, positional(context.args, 0, "thread"));
    return reportOutcome(context, client, thread.id, await waitOn(client, thread.id, { current: true }, timeoutSignal(context.args)));
  },
};

export const watch: Command = {
  name: "watch",
  summary: "Stream a thread's events as JSONL until interrupted. Default view: runs, final messages, requests, errors, plans, checkpoints.",
  usage: "watch <thread> [--raw] [--from <sequence>]",
  flags: {
    raw: { type: "boolean", help: "emit every stream item unchanged" },
    from: { type: "string", value: "sequence", help: "replay events after this sequence instead of starting live" },
  },
  async run({ client: connect, args, printLine }) {
    const client = await connect();
    const thread = await lookupThread(client, positional(args, 0, "thread"));
    const from = intFlag(args, "from");
    const controller = new AbortController();
    process.once("SIGINT", () => controller.abort());
    const payload = from === undefined ? { threadId: thread.id } : { threadId: thread.id, afterSequence: from };
    for await (const wireItem of client.stream("orchestration.subscribeThread", payload, controller.signal)) {
      const item = wireItem as StreamItem;
      if (boolFlag(args, "raw")) {
        printLine(item);
      } else if (item.kind === "snapshot") {
        const { projection, snapshotSequence } = item;
        const run = currentRun(projection.runs);
        printLine({ type: "snapshot", threadId: projection.thread.id, title: projection.thread.title, runId: run?.id ?? null, status: run?.status ?? null, sequence: snapshotSequence });
      } else if (item.kind === "event") {
        const summary = summarizeEvent(item);
        if (summary) printLine({ sequence: item.sequence, at: item.event.occurredAt, ...summary });
      }
    }
  },
};

export const interrupt: Command = {
  name: "interrupt",
  summary: "Interrupt the running turn. Queued messages start afterwards unless --hold-queue is passed.",
  usage: "interrupt <thread> [--hold-queue]",
  flags: { "hold-queue": { type: "boolean", help: "also hold queued messages, like the Stop button" } },
  async run({ client: connect, args, print }) {
    const client = await connect();
    const thread = await lookupThread(client, positional(args, 0, "thread"));
    const run = await activeRun(client, thread.id);
    if (!run) throw new T3Error(`${thread.id} has no running turn`);
    const result = await client.dispatch({ type: "run.interrupt", threadId: thread.id, runId: run.id, holdQueue: boolFlag(args, "hold-queue") || undefined });
    print({ runId: run.id, ...result }, () => `interrupt requested on ${thread.id} (run ${run.ordinal})`);
  },
};

async function activeRun(client: T3Client, threadId: string) {
  const run = currentRun((await client.thread(threadId)).runs);
  return run && isActive(run) ? run : undefined;
}

export const approve: Command = {
  name: "approve",
  summary: "Respond to an approval request (see: t3c pending).",
  usage: `approve <thread> [<requestId>] --decision <${APPROVAL_DECISIONS.join("|")}>`,
  flags: { decision: { type: "string", value: "decision", help: APPROVAL_DECISIONS.join(", ") } },
  async run({ client: connect, args, print }) {
    const decision = enumFlag(args, "decision", APPROVAL_DECISIONS);
    if (!decision) throw new UsageError("--decision is required");
    const client = await connect();
    const thread = await lookupThread(client, positional(args, 0, "thread"));
    const requestId = await requestIdArg(client, thread.id, args.positionals[1]);
    print(await client.dispatch({ type: "runtime-request.respond", threadId: thread.id, requestId, decision }), () => `${decision} sent for ${requestId}`);
  },
};

export const answer: Command = {
  name: "answer",
  summary: "Answer a user-input request (see: t3c pending). Answers are keyed by question id.",
  usage: "answer <thread> [<requestId>] --answer <questionId=value>... | --dismiss",
  flags: {
    answer: { type: "string", value: "questionId=value", multiple: true, help: "answer for one question, repeatable" },
    dismiss: { type: "boolean", help: "dismiss the request without answering" },
  },
  async run({ client: connect, args, print }) {
    const answers = Object.fromEntries(parseKeyValues("answer", listFlag(args, "answer")).map(({ id, value }) => [id, value]));
    const dismiss = boolFlag(args, "dismiss");
    if (!dismiss && Object.keys(answers).length === 0) throw new UsageError("pass --answer questionId=value or --dismiss");
    const client = await connect();
    const thread = await lookupThread(client, positional(args, 0, "thread"));
    const requestId = await requestIdArg(client, thread.id, args.positionals[1]);
    if (dismiss) {
      print(await client.dispatch({ type: "thread.user-input.dismiss", threadId: thread.id, requestId }), () => `dismissed ${requestId}`);
      return;
    }
    print(await client.dispatch({ type: "runtime-request.respond", threadId: thread.id, requestId, answers }), () => `answered ${requestId}`);
  },
};

/** The given request id, or the thread's only pending request when none is given. */
async function requestIdArg(client: T3Client, threadId: string, given: string | undefined): Promise<string> {
  if (given) return given;
  const pending = pendingRequests(await client.thread(threadId));
  if (pending.length === 1) return pending[0]!.request.id;
  throw new UsageError(pending.length === 0 ? `${threadId} has no pending requests` : `${threadId} has ${pending.length} pending requests; pass a requestId (see: t3c pending)`);
}

export const close: Command = {
  name: "close",
  summary: "Interrupt if running (holding queued messages), wait for the turn to settle, then settle the thread. Reopen with unsettle or send.",
  usage: "close <thread> [--timeout <duration>]",
  flags: { timeout: { type: "string", value: "duration", help: "give up waiting for the interrupt after e.g. 2m (default 2m)" } },
  async run({ client: connect, args, print }) {
    const client = await connect();
    const thread = await lookupThread(client, positional(args, 0, "thread"));
    const run = await activeRun(client, thread.id);
    if (run) {
      await client.dispatch({ type: "run.interrupt", threadId: thread.id, runId: run.id, holdQueue: true });
      if (!(await waitOn(client, thread.id, { current: true }, timeoutSignal(args, "2m")))) throw new T3Error(`${thread.id} did not stop in time; not settled`, EXIT.timeout);
    }
    const result = await client.dispatch({ type: "thread.settle", threadId: thread.id });
    print({ threadId: thread.id, interrupted: Boolean(run), ...result }, () => `${thread.id} settled${run ? " (after interrupt)" : ""}`);
  },
};
